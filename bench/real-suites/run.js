#!/usr/bin/env node
"use strict";
// Runs real open-source Jest/Vitest suites (manifest.js) with jsdom (each project's own version and environment), jsdom
// 30.1.2 (rsdom's upstream, through rsdom's own integration code), rsdom (this worktree, native build) and happy-dom,
// measuring wall time and comparing per-test results. rsdom's compatibility reference is jsdom 30.1.2: differences
// between a project's older jsdom and 30.1.2 are jsdom version changes, not rsdom bugs.
//
//   node run.js setup  [--only a,b]               clone at the pinned commits into .cache/, install, write wrappers
//   node run.js bench  [--only a,b] [--impls jsdom,jsdom30,rsdom,happy-dom] [--runs 3] [--warmups 1]
//                                                 writes results/<timestamp>.json
//   node run.js profile --only a [--impl rsdom]   CPU-profiles one run (every process) and prints a breakdown
//   node run.js analyze --only a [--impl rsdom]   re-analyzes the profiles of the last profile run
//   node run.js frames --only a [--impls ...]     Vitest only: share of each test file's time spent waiting for
//                                                 requestAnimationFrame callbacks
//   node run.js report [results/a.json b.json]    prints the markdown table for the README (later files win per project)
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const { spawn, spawnSync } = require("node:child_process");
const manifest = require("./manifest.js");
const { analyzeProfiles, formatBreakdown } = require("./lib/profile.js");

const HERE = __dirname;
const REPO_ROOT = path.resolve(HERE, "../..");
const CACHE = path.join(HERE, ".cache");
const OUT = path.join(CACHE, "out");
const RESULTS = path.join(HERE, "results");
const ALL_IMPLS = ["jsdom", "jsdom30", "rsdom", "happy-dom"];
const RUN_TIMEOUT_MS = 20 * 60 * 1000;

function parseArgs(argv) {
  const args = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith("--")) {
      const [k, v] = a.slice(2).split("=");
      args[k] = v ?? (argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[++i] : true);
    } else {
      args._.push(a);
    }
  }
  return args;
}

function projectsFor(args) {
  const only = args.only ? String(args.only).split(",") : null;
  const list = only ? manifest.filter(p => only.includes(p.name)) : manifest;
  if (only && list.length !== only.length) {
    throw new Error(`unknown project in --only ${args.only}; known: ${manifest.map(p => p.name).join(", ")}`);
  }
  return list;
}

const dirOf = project => path.join(CACHE, project.dir ?? project.name);

function sh(cmd, argv, opts) {
  const r = spawnSync(cmd, argv, { stdio: "inherit", ...opts });
  if (r.status !== 0) {
    throw new Error(`${cmd} ${argv.join(" ")} failed (${r.status})`);
  }
}

function git(dir, ...argv) {
  return spawnSync("git", argv, { cwd: dir, encoding: "utf8" }).stdout.trim();
}

function wrapperSource(project) {
  const rel = `./${path.basename(project.config)}`;
  const lib = path.join(HERE, "lib/swap.mjs");
  const fn = project.runner === "jest" ? "swapJestConfig" : "swapVitestConfig";
  const header = "// Generated by bench/real-suites/run.js: the project's config with its DOM environment swapped for " +
    "REAL_SUITES_IMPL.\n";
  if (project.runner === "jest") {
    return `${header}import { ${fn} } from ${JSON.stringify(lib)};\nimport * as original from ${JSON.stringify(rel)};\n\n` +
      `// A function, not top-level await: Jest 29 require()s .mjs configs first, which fails on top-level await.\n` +
      `export default () => ${fn}(original.default ?? original);\n`;
  }
  return `${header}import { ${fn} } from ${JSON.stringify(lib)};\nimport original from ${JSON.stringify(rel)};\n\n` +
    `export default (env: unknown) => ${fn}(original, env);\n`;
}

function setup(args) {
  for (const project of projectsFor(args)) {
    const dir = dirOf(project);
    if (!fs.existsSync(path.join(dir, ".git"))) {
      fs.mkdirSync(dir, { recursive: true });
      sh("git", ["init", "-q"], { cwd: dir });
      sh("git", ["remote", "add", "origin", project.repo], { cwd: dir });
    }
    if (git(dir, "rev-parse", "HEAD") !== project.commit) {
      sh("git", ["fetch", "-q", "--depth", "1", "origin", project.commit], { cwd: dir });
      sh("git", ["checkout", "-q", "--force", project.commit], { cwd: dir });
    }
    if (!fs.existsSync(path.join(dir, "node_modules")) || args.reinstall) {
      for (const [cmd, ...argv] of project.install) {
        sh(cmd, argv, { cwd: dir, env: { ...process.env, CI: "1" } });
      }
    }
    fs.writeFileSync(path.join(dir, project.wrapper), wrapperSource(project));
    console.log(`${project.name}: ready at ${git(dir, "rev-parse", "--short", "HEAD")}`);
  }
}

function versionIn(dir, pkg, via = []) {
  // Resolves pkg the way the project's environment does: from the project, or through a chain of packages.
  let base = path.join(dir, "package.json");
  try {
    for (const step of via) {
      base = require.resolve(`${step}/package.json`, { paths: [path.dirname(base)] });
    }
    return require(require.resolve(`${pkg}/package.json`, { paths: [path.dirname(base)] })).version;
  } catch {
    return null;
  }
}

function implVersions(project) {
  const dir = dirOf(project);
  const jsdom = versionIn(dir, "jsdom") ?? versionIn(dir, "jsdom", ["jest-environment-jsdom"]) ??
    versionIn(dir, "jsdom", ["kcd-scripts", "jest-environment-jsdom"]);
  return {
    "jsdom": jsdom,
    "jsdom30": require("jsdom-upstream/package.json").version,
    "rsdom": `${require(path.join(REPO_ROOT, "package.json")).version}@${git(REPO_ROOT, "rev-parse", "--short", "HEAD")}`,
    "happy-dom": require("happy-dom/package.json").version,
    "runner": `${project.runner} ${versionIn(dir, project.runner)}`
  };
}

// Runs are spawned in their own process group (see runOnce); take them down with the harness.
const activeRuns = new Set();
for (const signal of ["SIGINT", "SIGTERM"]) {
  process.once(signal, () => {
    for (const pid of activeRuns) {
      try {
        process.kill(-pid, "SIGKILL");
      } catch {
        // already gone
      }
    }
    process.kill(process.pid, signal);
  });
}

function runOnce(project, impl, tag, extraEnv = {}) {
  const dir = dirOf(project);
  fs.mkdirSync(OUT, { recursive: true });
  const base = path.join(OUT, `${project.name}.${impl}.${tag}`);
  const outFile = `${base}.json`;
  fs.rmSync(outFile, { force: true });
  const configPath = path.join(dir, project.wrapper);
  const [cmd, ...argv] = project.command.map(a => a.replace("{config}", configPath).replace("{out}", outFile));
  const log = fs.openSync(`${base}.log`, "w");
  const marker = `${base}.envs`;
  fs.rmSync(marker, { force: true });
  const env = {
    ...process.env,
    CI: "1",
    FORCE_COLOR: "0",
    ...project.env,
    REAL_SUITES_IMPL: impl,
    REAL_SUITES_PROJECT_DIR: dir,
    REAL_SUITES_ENV_MARKER: marker,
    ...extraEnv
  };
  delete env.JSDOM_NATIVE;
  return new Promise(resolve => {
    const start = process.hrtime.bigint();
    // Own process group, so a timeout kills the runner's workers too (a hung Vitest fork pool otherwise outlives it).
    const child = spawn(cmd, argv, { cwd: dir, env, stdio: ["ignore", log, log], detached: true });
    const timer = setTimeout(() => {
      console.error(`  !! ${project.name} ${impl}: timed out after ${RUN_TIMEOUT_MS / 60000} min, killing it`);
      try {
        process.kill(-child.pid, "SIGKILL");
      } catch {
        child.kill("SIGKILL");
      }
    }, RUN_TIMEOUT_MS);
    activeRuns.add(child.pid);
    child.on("exit", code => {
      clearTimeout(timer);
      activeRuns.delete(child.pid);
      fs.closeSync(log);
      const ms = Number(process.hrtime.bigint() - start) / 1e6;
      // Environments the harness created (jsdom runs use the project's own, so none).
      const envs = fs.existsSync(marker) ? fs.readFileSync(marker, "utf8").split("\n").filter(Boolean) : [];
      if (impl === "jsdom" ? envs.length !== 0 : envs.length === 0 || envs.some(e => e !== impl)) {
        console.error(`  !! ${project.name} ${impl}: unexpected environments created: ${envs.length} (${[...new Set(envs)]})`);
      }
      resolve({ ms, code, outFile, logFile: `${base}.log`, envCount: envs.length, results: readResults(outFile, dir) });
    });
  });
}

// Jest's --json and Vitest's json reporter share a format: testResults[] (one per file) with assertionResults[].
function readResults(file, dir) {
  if (!fs.existsSync(file)) {
    return null;
  }
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  const tests = {};
  const suiteErrors = {};
  let passed = 0, failed = 0, skipped = 0;
  for (const suite of data.testResults) {
    const rel = path.relative(dir, suite.name ?? suite.testFilePath);
    const assertions = suite.assertionResults ?? [];
    if (suite.status === "failed" && !assertions.some(a => a.status === "failed")) {
      suiteErrors[rel] = (suite.message ?? suite.failureMessage ?? "").slice(0, 2000);
    }
    for (const a of assertions) {
      const key = `${rel} > ${a.fullName ?? [...(a.ancestorTitles ?? []), a.title].join(" ")}`;
      if (a.status === "passed") {
        passed++;
      } else if (a.status === "failed") {
        failed++;
      } else {
        skipped++;
      }
      tests[key] = { status: a.status, message: a.status === "failed" ? (a.failureMessages ?? []).join("\n").slice(0, 1500) : undefined };
    }
  }
  return { passed, failed, skipped, suiteErrors, tests };
}

const median = xs => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2;
};

// A test counts as passing for an impl only if it passed in every run; a test that both passed and failed is flaky.
function summarizeImpl(runs) {
  const statuses = new Map();
  for (const run of runs) {
    for (const [key, { status, message }] of Object.entries(run.results?.tests ?? {})) {
      const entry = statuses.get(key) ?? { seen: new Set(), message: undefined };
      entry.seen.add(status);
      if (message) {
        entry.message = message;
      }
      statuses.set(key, entry);
    }
  }
  return statuses;
}

function compare(baseline, other) {
  const regressions = [];
  const flakyHere = [];
  for (const [key, b] of baseline) {
    if (!(b.seen.size === 1 && b.seen.has("passed"))) {
      continue;
    }
    const o = other.get(key);
    if (!o) {
      regressions.push({ test: key, status: "missing (file failed to run?)" });
    } else if (o.seen.has("failed") && o.seen.has("passed")) {
      flakyHere.push({ test: key, message: o.message });
    } else if (!o.seen.has("passed")) {
      regressions.push({ test: key, status: [...o.seen].join("/"), message: o.message });
    }
  }
  const fixes = [];
  for (const [key, o] of other) {
    const b = baseline.get(key);
    if (b && b.seen.has("failed") && !b.seen.has("passed") && o.seen.size === 1 && o.seen.has("passed")) {
      fixes.push(key);
    }
  }
  return { regressions, flaky: flakyHere, passesOnlyHere: fixes };
}

async function bench(args) {
  const impls = args.impls ? String(args.impls).split(",") : ALL_IMPLS;
  const runs = Number(args.runs ?? 3);
  const warmups = Number(args.warmups ?? 1);
  const results = {
    date: new Date().toISOString(),
    machine: { cpu: os.cpus()[0].model, cores: os.cpus().length, platform: `${process.platform} ${process.arch}`,
      node: process.version, loadavgAtStart: os.loadavg() },
    rsdomCommit: git(REPO_ROOT, "rev-parse", "HEAD"),
    method: `${warmups} warmup run(s) per impl, then ${runs} timed rounds; each round runs every impl once, in an ` +
      "order rotated per round. Wall time of the whole runner process. Per-test results come from every run.",
    projects: []
  };
  for (const project of projectsFor(args)) {
    console.log(`\n== ${project.name}`);
    const perImpl = Object.fromEntries(impls.map(i => [i, { times: [], runs: [] }]));
    for (let w = 0; w < warmups; w++) {
      for (const impl of impls) {
        const r = await runOnce(project, impl, `warmup${w}`);
        perImpl[impl].runs.push(r);
        console.log(`  warmup ${impl}: ${(r.ms / 1000).toFixed(1)}s exit ${r.code} ${fmtCounts(r.results)}, ` +
          `${r.envCount} envs`);
      }
    }
    for (let round = 0; round < runs; round++) {
      const order = impls.map((_, i) => impls[(i + round) % impls.length]);
      for (const impl of order) {
        const r = await runOnce(project, impl, `run${round}`);
        perImpl[impl].runs.push(r);
        perImpl[impl].times.push(r.ms);
        console.log(`  round ${round} ${impl}: ${(r.ms / 1000).toFixed(1)}s exit ${r.code} ${fmtCounts(r.results)}, ` +
          `${r.envCount} envs`);
      }
    }
    const statuses = Object.fromEntries(impls.map(i => [i, summarizeImpl(perImpl[i].runs)]));
    const entry = {
      name: project.name, repo: project.repo, commit: project.commit, runner: project.runner,
      command: project.command.join(" "), notes: project.notes, versions: implVersions(project), impls: {}
    };
    for (const impl of impls) {
      const { times, runs: implRuns } = perImpl[impl];
      const last = implRuns.at(-1).results;
      const allPass = [...statuses[impl].values()].filter(s => s.seen.size === 1 && s.seen.has("passed")).length;
      entry.impls[impl] = {
        minMs: Math.round(Math.min(...times)),
        medianMs: Math.round(median(times)),
        timesMs: times.map(Math.round),
        tests: last ? { passed: last.passed, failed: last.failed, skipped: last.skipped } : null,
        passedInEveryRun: allPass,
        suiteErrors: last ? last.suiteErrors : null,
        exitCodes: implRuns.map(r => r.code)
      };
      if (impl !== "jsdom" && statuses.jsdom) {
        entry.impls[impl].vsJsdom = compare(statuses.jsdom, statuses[impl]);
      }
      // rsdom's compatibility reference: jsdom 30.1.2 (its upstream) through the same environment code.
      if (impl !== "jsdom" && impl !== "jsdom30" && statuses.jsdom30) {
        entry.impls[impl].vsJsdom30 = compare(statuses.jsdom30, statuses[impl]);
      }
    }
    results.projects.push(entry);
    printProject(entry);
  }
  fs.mkdirSync(RESULTS, { recursive: true });
  const file = path.join(RESULTS, `${results.date.replace(/[:.]/g, "-")}.json`);
  fs.writeFileSync(file, `${JSON.stringify(results, null, 2)}\n`);
  console.log(`\nwrote ${path.relative(process.cwd(), file)}\n`);
  console.log(markdownTable(results));
}

function fmtCounts(r) {
  if (!r) {
    return "(no results file)";
  }
  const errs = Object.keys(r.suiteErrors).length;
  return `${r.passed} passed, ${r.failed} failed, ${r.skipped} skipped${errs ? `, ${errs} files errored` : ""}`;
}

function printProject(entry) {
  for (const [impl, r] of Object.entries(entry.impls)) {
    console.log(`  ${impl.padEnd(10)} min ${(r.minMs / 1000).toFixed(2)}s median ${(r.medianMs / 1000).toFixed(2)}s`);
    for (const [label, v] of [["jsdom", r.vsJsdom], ["jsdom30", r.vsJsdom30]]) {
      if (!v) {
        continue;
      }
      console.log(`    vs ${label}: ${v.regressions.length} regressions, ${v.flaky.length} flaky, ` +
        `${v.passesOnlyHere.length} pass only here`);
      for (const reg of v.regressions.slice(0, 10)) {
        console.log(`      - ${reg.test}: ${reg.status}`);
      }
    }
  }
}

function markdownTable(results) {
  const rows = [
    "| Project | Runner | Project's jsdom | jsdom (s) | jsdom 30.1.2 (s) | rsdom (s) | happy-dom (s) | " +
      "rsdom speedup vs jsdom / jsdom 30 | rsdom vs happy-dom | Tests passed: jsdom / jsdom 30 / rsdom / happy-dom | " +
      "rsdom regressions vs jsdom 30 |",
    "|---|---|---|--:|--:|--:|--:|--:|--:|---|--:|"
  ];
  const sec = r => (r ? (r.minMs / 1000).toFixed(1) : "–");
  for (const p of results.projects) {
    const { jsdom, jsdom30, rsdom } = p.impls;
    const happy = p.impls["happy-dom"];
    const counts = ["jsdom", "jsdom30", "rsdom", "happy-dom"].map(i => {
      const t = p.impls[i]?.tests;
      if (!t) {
        return "–";
      }
      const errs = Object.keys(p.impls[i].suiteErrors ?? {}).length;
      return `${t.passed}${t.failed ? ` (${t.failed} failed)` : ""}${errs ? ` (${errs} files errored)` : ""}`;
    }).join(" / ");
    const ratio = (a, b) => (a && b ? `${(a.minMs / b.minMs).toFixed(2)}x` : "–");
    rows.push(`| [${p.name}](${p.repo}/tree/${p.commit.slice(0, 10)}) | ${p.versions.runner} | ${p.versions.jsdom} | ` +
      `${sec(jsdom)} | ${sec(jsdom30)} | ${sec(rsdom)} | ${sec(happy)} | ${ratio(jsdom, rsdom)} / ${ratio(jsdom30, rsdom)} | ` +
      `${ratio(happy, rsdom)} | ${counts} | ${rsdom?.vsJsdom30?.regressions.length ?? "–"} |`);
  }
  return rows.join("\n");
}

// With several files, a project measured in a later file replaces its row from an earlier one (e.g. a re-run of one
// noisy project with more rounds), in manifest order.
function report(args) {
  const files = args._.length > 1 ? args._.slice(1) :
    [fs.readdirSync(RESULTS).filter(f => /^\d.*\.json$/.test(f)).sort().map(f => path.join(RESULTS, f)).at(-1)];
  const byName = new Map();
  for (const file of files) {
    for (const p of JSON.parse(fs.readFileSync(file, "utf8")).projects) {
      byName.set(p.name, p);
    }
  }
  const projects = manifest.map(m => byName.get(m.name)).filter(Boolean);
  console.log(markdownTable({ projects }));
}

async function profile(args) {
  const impl = args.impl ?? "rsdom";
  const results = [];
  for (const project of projectsFor(args)) {
    const profDir = path.join(CACHE, "profiles", `${project.name}.${impl}`);
    fs.rmSync(profDir, { recursive: true, force: true });
    fs.mkdirSync(profDir, { recursive: true });
    // NODE_OPTIONS reaches the runner and every worker process (both runners default to child-process workers); the
    // hook profiles each process and writes its profile however the pool ends it (see lib/cpu-profile-hook.cjs).
    const hook = path.join(HERE, "lib/cpu-profile-hook.cjs");
    const nodeOptions = `${process.env.NODE_OPTIONS ?? ""} --require=${hook}`;
    const r = await runOnce(project, impl, "profile", {
      NODE_OPTIONS: nodeOptions.trim(), REAL_SUITES_PROFILE_DIR: profDir, REAL_SUITES_PROFILE_INTERVAL_US: "500"
    });
    console.log(`${project.name} (${impl}): ${(r.ms / 1000).toFixed(1)}s with profiling, exit ${r.code} ${fmtCounts(r.results)}`);
    const breakdown = analyzeProfiles(profDir, { projectDir: dirOf(project), repoRoot: REPO_ROOT, impl });
    console.log(formatBreakdown(breakdown));
    results.push({ name: project.name, impl, wallMs: Math.round(r.ms), breakdown });
  }
  fs.mkdirSync(RESULTS, { recursive: true });
  const names = results.map(r => r.name).join("+");
  const file = path.join(RESULTS, `profile-${names}-${impl}-${new Date().toISOString().replace(/[:.]/g, "-")}.json`);
  fs.writeFileSync(file, `${JSON.stringify(results, null, 2)}\n`);
  console.log(`wrote ${path.relative(process.cwd(), file)}`);
}

// Re-analyzes the profiles of the last `profile` run (e.g. after changing lib/profile.js) without running again.
function analyze(args) {
  const impl = args.impl ?? "rsdom";
  for (const project of projectsFor(args)) {
    const profDir = path.join(CACHE, "profiles", `${project.name}.${impl}`);
    console.log(`${project.name} (${impl}):`);
    console.log(formatBreakdown(analyzeProfiles(profDir, { projectDir: dirOf(project), repoRoot: REPO_ROOT, impl })));
  }
}

// Measures how much of each Vitest test file's time is spent waiting for requestAnimationFrame callbacks (see
// recordFrameWaits in lib/vitest-env.mjs). One run per impl; the project's own jsdom is skipped, since its environment
// is not the harness's.
async function frames(args) {
  // happy-dom is not measured by default: with the wrapper installed, ariakit's suite collected 129 fewer tests and made
  // only 18 rAF calls under happy-dom, so the numbers would not be comparable.
  const impls = args.impls ? String(args.impls).split(",") : ["jsdom30", "rsdom"];
  const results = [];
  for (const project of projectsFor(args)) {
    if (project.runner !== "vitest") {
      console.log(`${project.name}: skipped (frame-wait measurement is Vitest only)`);
      continue;
    }
    for (const impl of impls.filter(i => i !== "jsdom")) {
      const statsFile = path.join(OUT, `${project.name}.${impl}.frames.jsonl`);
      fs.mkdirSync(OUT, { recursive: true });
      fs.rmSync(statsFile, { force: true });
      const r = await runOnce(project, impl, "frames", { REAL_SUITES_FRAME_STATS: statsFile });
      const lines = fs.existsSync(statsFile) ?
        fs.readFileSync(statsFile, "utf8").split("\n").filter(Boolean).map(l => JSON.parse(l)) :
        [];
      const sum = key => lines.reduce((a, l) => a + l[key], 0);
      const row = {
        name: project.name, impl, wallMs: Math.round(r.ms), files: lines.length, envMs: Math.round(sum("envMs")),
        framePendingMs: Math.round(sum("framePendingMs")), rafCalls: sum("rafCalls")
      };
      row.framePendingPct = Math.round(1000 * row.framePendingMs / row.envMs) / 10;
      results.push(row);
      console.log(`${project.name} (${impl}): ${(r.ms / 1000).toFixed(1)}s wall, ${fmtCounts(r.results)}; ${row.files} ` +
        `files, ${(row.envMs / 1000).toFixed(1)}s in test-file environments, of which ` +
        `${(row.framePendingMs / 1000).toFixed(1)}s (${row.framePendingPct}%) with a requestAnimationFrame callback ` +
        `pending; ${row.rafCalls} rAF calls`);
    }
  }
  fs.mkdirSync(RESULTS, { recursive: true });
  const file = path.join(RESULTS, `frames-${new Date().toISOString().replace(/[:.]/g, "-")}.json`);
  fs.writeFileSync(file, `${JSON.stringify(results, null, 2)}\n`);
  console.log(`wrote ${path.relative(process.cwd(), file)}`);
}

const args = parseArgs(process.argv.slice(2));
const commands = { setup, bench, profile, analyze, report, frames };
const command = commands[args._[0]];
if (!command) {
  console.error("usage: node run.js setup|bench|profile|analyze|report|frames [--only a,b] (see the header of run.js)");
  process.exit(2);
}
Promise.resolve(command(args)).catch(e => {
  console.error(e);
  process.exit(1);
});
